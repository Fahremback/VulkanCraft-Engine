int main() {
    using namespace Engine::Rendering;

    // --- open(): real KTX2 description ---
    {
        auto tx = create_ktx2_transcoder();
        Ktx2Info info;
        std::string err;
        check(tx->open(kBlzeKtx2, sizeof(kBlzeKtx2), info, err),
              "open: valid KTX2 accepted");
        check(info.width == 8 && info.height == 8, "open: 8x8");
        check(info.levels == 1, "open: 1 level");
        check(info.faces == 1, "open: 1 face (2D)");
        check(!info.uastc, "open: ETC1S payload (not UASTC)");
    }

    // --- transcodeLevel: RGBA32, correct size, deterministic ---
    {
        auto tx = create_ktx2_transcoder();
        Ktx2Info info;
        std::string err;
        check(tx->open(kBlzeKtx2, sizeof(kBlzeKtx2), info, err),
              "rgba: open ok");
        std::vector<std::uint8_t> a, b;
        check(tx->transcodeLevel(0, 0, Ktx2Format::Rgba32, a, err),
              "rgba: transcode ok");
        check(a.size() == 8 * 8 * 4, "rgba: 256 bytes (8x8x4)");
        // Golden value from the vendor asset: this blend-test image decodes to
        // a constant mid-alpha 0x80 with per-channel color (0xab, 0xbb, 0xcc).
        check(a[0] == 0xab && a[1] == 0xbb && a[2] == 0xcc && a[3] == 0x80,
              "rgba: golden first pixel (ab bb cc 80)");
        check(tx->transcodeLevel(0, 0, Ktx2Format::Rgba32, b, err),
              "rgba: second transcode ok");
        check(a == b, "rgba: bit-exact deterministic decode");
    }

    // --- transcodeLevel: BC7 block format (2x2 blocks x 16 bytes) ---
    {
        auto tx = create_ktx2_transcoder();
        Ktx2Info info;
        std::string err;
        check(tx->open(kBlzeKtx2, sizeof(kBlzeKtx2), info, err),
              "bc7: open ok");
        std::vector<std::uint8_t> out;
        check(tx->transcodeLevel(0, 0, Ktx2Format::Bc7Rgba, out, err),
              "bc7: transcode ok");
        check(out.size() == 2 * 2 * 16, "bc7: 64 bytes (2x2 blocks)");
    }

    // --- refusals: all-or-nothing, diagnostics, out untouched ---
    {
        auto tx = create_ktx2_transcoder();
        Ktx2Info info;
        std::string err;
        check(!tx->open(nullptr, 0, info, err), "null data refused");
        check(!err.empty(), "null data diagnostic present");
        check(!tx->open(kBlzeKtx2, 32, info, err), "truncated refused");
        check(tx->open(kBlzeKtx2, sizeof(kBlzeKtx2), info, err),
              "full-size accepted (sanity)");
    }

    // --- transcode before open refused, out untouched (fresh instance) ---
    {
        auto tx = create_ktx2_transcoder();
        std::string err;
        std::vector<std::uint8_t> out;
        std::vector<std::uint8_t> sentinel(4, 0xAA);
        out = sentinel;
        check(!tx->transcodeLevel(0, 0, Ktx2Format::Rgba32, out, err),
              "transcode before open refused");
        check(out == sentinel, "refused transcode leaves out untouched");
    }

    // --- level/face out of range refused ---
    {
        auto tx = create_ktx2_transcoder();
        Ktx2Info info;
        std::string err;
        check(tx->open(kBlzeKtx2, sizeof(kBlzeKtx2), info, err),
              "range: open ok");
        std::vector<std::uint8_t> out;
        check(!tx->transcodeLevel(1, 0, Ktx2Format::Rgba32, out, err),
              "level 1 (only 1 level) refused");
        check(!tx->transcodeLevel(0, 1, Ktx2Format::Rgba32, out, err),
              "face 1 (only 1 face) refused");
    }

    // --- corrupted magic rejected ---
    {
        auto tx = create_ktx2_transcoder();
        std::vector<std::uint8_t> bad(kBlzeKtx2, kBlzeKtx2 + sizeof(kBlzeKtx2));
        bad[1] = 0xFF;  // break the "KTX 20" magic
        Ktx2Info info;
        std::string err;
        check(!tx->open(bad.data(), bad.size(), info, err),
              "corrupted magic refused");
        check(!err.empty(), "corrupted magic diagnostic present");
    }

    if (g_failures == 0) {
        std::printf("Ktx2TranscoderTests: ALL PASSED\n");
        return 0;
    }
    std::printf("Ktx2TranscoderTests: %d FAILURE(S)\n", g_failures);
    return 1;
}
